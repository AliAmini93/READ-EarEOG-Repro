"""SYNTHETIC recordings for the tests (test fixtures only).

Everything produced here is generated from a simple, explicitly stated model and has no relation to any real
recording or person. Results computed on synthetic data demonstrate that the code runs and behaves as specified;
they are NOT the article's results and must never be reported as such.

Model: a reader fixates words along lines of a page; forward saccades move gaze right, return sweeps move it to the
start of the next line, occasional regressions move it left. The ear "channels" carry a common horizontal signal
proportional to gaze x (opposite signs on the two sides), plus independent noise and slow drift per channel.
"""
from __future__ import annotations

import numpy as np

from .config import PROTOCOL, Protocol
from .recording import Recording

SYNTHETIC_NOTICE = 'SYNTHETIC DATA - generated by read_eareog.synthetic; not a recording of any person'


def synthetic_recording(seed: int, minutes: float = 3.0, fs: float = 500.0, gain: float = 0.02, noise: float = 1.0,
                        regression_rate: float = 0.10, name: str | None = None, protocol: Protocol = PROTOCOL) -> Recording:
    """Generate one synthetic recording (see module docstring). ``gain`` is the ear signal per screen px."""
    rng = np.random.default_rng(seed)
    pitch = protocol.line_pitch_px
    lead_in = 20.0                                   # seconds of data before W (padding for filters and scaling)
    t_end = lead_in + minutes * 60.0 + 20.0
    fix, sac, blinks = [], [], []
    t, y = lead_in - 5.0, 120.0
    x_left, x_right = 120.0, 1250.0
    x = x_left + rng.uniform(0, 30)
    while t < t_end - 25.0:
        while x < x_right and t < t_end - 25.0:
            d = rng.uniform(0.18, 0.30) if rng.uniform() > 0.12 else rng.uniform(0.6, 1.0)   # some long fixations
            fix.append((t, d, x + rng.normal(0, 4), y + rng.normal(0, 3)))
            if d > 0.5 and rng.uniform() < 0.3:
                blinks.append(t + d / 2)                    # blink inside a long fixation
            t += d
            u = rng.uniform()
            if u < 0.03 and y > 120.0 + pitch:              # regression to the previous line and back
                dx = -rng.uniform(100, 600)
                sac.append((t, 0.04, dx, -pitch))
                t += 0.04
                for j in range(3):                          # re-read three words of the previous line
                    fix.append((t, 0.22, x + dx + 60 * j, y - pitch + rng.normal(0, 3)))
                    t += 0.22
                    if j < 2:
                        sac.append((t, 0.02, 60.0, 0.0))
                        t += 0.02
                sac.append((t, 0.04, -dx - 120.0, pitch))
                t += 0.04
                continue
            if u < regression_rate and x > x_left + 200:
                dx = -rng.uniform(60, 420)                  # same-line regressions of varied size (some exceed 300 px)
            else:
                dx = rng.uniform(90, 200)
            sd = 0.02 + abs(dx) / 30000
            sac.append((t, sd, dx, rng.normal(0, 2)))
            t += sd
            x += dx
        sd = 0.045
        land = x_left + (rng.uniform(0, 260) if rng.uniform() > 0.05 else rng.uniform(350, 600))   # varied landing
        dy = pitch * (2 if rng.uniform() < 0.05 else 1)
        sac.append((t, sd, land - x, dy))                   # return sweep (or a skip of one line)
        t += sd
        x, y = land, y + dy
        if y > 900:                                         # next page
            fix.append((t, 0.2, x, y))
            t += 0.2
            sac.append((t, 0.05, x_left - x, 120.0 - y))
            t += 0.05
            x, y = x_left + rng.uniform(0, 30), 120.0
        if rng.uniform() < 0.15:
            blinks.append(t + rng.uniform(0.05, 0.15))
    F = {k: np.array([f[i] for f in fix]) for i, k in enumerate(('onset', 'duration', 'x', 'y'))}
    S = {k: np.array([s[i] for s in sac]) for i, k in enumerate(('onset', 'duration', 'dx', 'dy'))}
    n = int(t_end * fs)
    tt = np.arange(n) / fs
    gx = np.full(n, np.nan)                               # gaze x trace from fixations, held through saccades
    for o, d, x, _ in fix:
        gx[int(o * fs):int((o + d) * fs) + 1] = x
    first = np.flatnonzero(np.isfinite(gx))[0]
    gx[:first] = gx[first]
    for i in range(1, n):
        if not np.isfinite(gx[i]):
            gx[i] = gx[i - 1]
    gx = gx - np.median(gx)
    labels = list(protocol.left_ear) + list(protocol.right_ear) + [protocol.mastoid_left, protocol.mastoid_right,
                                                                    protocol.forehead]
    data = np.empty((len(labels), n))
    for i, lab in enumerate(labels):
        # corneo-retinal dipole: leftward gaze (x decreasing) makes the left-ear electrodes positive
        side = -0.5 if lab in protocol.left_ear else (0.5 if lab in protocol.right_ear else 0.0)
        drift = np.cumsum(rng.normal(0, 0.02, n)) / np.sqrt(fs)
        data[i] = side * gain * gx + rng.normal(0, noise, n) + drift
    return Recording(name=name or f'synthetic{seed:03d}', ear=data, ear_labels=labels, fs=fs, t=tt,
                     window=(lead_in, lead_in + minutes * 60.0), saccades=S, fixations=F, blinks=np.array(blinks),
                     synthetic=True)


def synthetic_cohort(n: int = 6, seed: int = 1, **kw) -> list:
    """``n`` synthetic recordings with seeds seed, seed + 1, ...; gain varies across recordings."""
    rng = np.random.default_rng(seed)
    return [synthetic_recording(seed + i, gain=float(rng.uniform(0.012, 0.03)), **kw) for i in range(n)]
